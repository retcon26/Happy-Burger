#!/usr/bin/env python3
"""Writes psp/src/certs.h: the root certificates the updater (psp/src/update.c) trusts for GitHub.

GitHub's API and github.com chain to USERTrust ECC (Sectigo), and its download hosts
(release-assets.githubusercontent.com, raw.githubusercontent.com) to ISRG Root X1 (Let's Encrypt).
A few more big roots are kept in case GitHub changes certificate authority.

Run it on Linux (or WSL) with the ca-certificates package:  python3 tools/update_certs.py
"""
import os
import re
import subprocess
import sys

BUNDLE = "/etc/ssl/certs/ca-certificates.crt"
WANT = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "GlobalSign Root CA - R3",
    "GTS Root R1",
    "GTS Root R4",
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "psp", "src", "certs.h")


def subject_cn(pem):
    out = subprocess.run(["openssl", "x509", "-noout", "-subject", "-enddate", "-nameopt", "multiline"],
                         input=pem.encode(), capture_output=True, check=True).stdout.decode()
    cn = re.search(r"commonName\s*=\s*(.+)", out)
    end = re.search(r"notAfter=(.+)", out)
    return (cn.group(1).strip() if cn else ""), (end.group(1).strip() if end else "")


def main():
    text = open(BUNDLE).read()
    pems = re.findall(r"-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----", text, re.S)
    found = {}
    for pem in pems:
        cn, end = subject_cn(pem)
        # GlobalSign R3's CN is just "GlobalSign"; tell it apart by its organisational unit
        if cn == "GlobalSign":
            ou = subprocess.run(["openssl", "x509", "-noout", "-subject"], input=pem.encode(),
                                capture_output=True).stdout.decode()
            if "Root CA - R3" in ou:
                cn = "GlobalSign Root CA - R3"
        if cn in WANT and cn not in found:
            found[cn] = (pem, end)
    missing = [n for n in WANT if n not in found]
    if missing:
        print("not in the bundle (left out):", ", ".join(missing), file=sys.stderr)
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/update_certs.py: the root certificates update.c trusts (PEM, one string).",
        "// GitHub's API and github.com chain to USERTrust ECC; its download hosts to ISRG Root X1.",
    ]
    for n in WANT:
        if n in found:
            lines.append(f"//   {n} (until {found[n][1]})")
    lines.append("static const char k_root_certs[] =")
    for n in WANT:
        if n not in found:
            continue
        for row in found[n][0].strip().splitlines():
            lines.append(f'    "{row}\\n"')
    lines[-1] += ";"
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(found)} roots -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
